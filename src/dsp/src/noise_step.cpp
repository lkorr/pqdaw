const float kNoiseColourPoles[kNoiseColourSections] = {kPoles[0], kPoles[1], kPoles[2], kPoles[3]};

NoiseColourDesign noiseColourDesign(float c) noexcept {  // RT-safe
  NoiseColourDesign d;
  if (!(c == c) || c == 0.0f) return d;  // NaN, ±0: white
  c = c < kNoiseColourMin ? kNoiseColourMin : c > kNoiseColourMax ? kNoiseColourMax : c;
  const float x = (c - kNoiseColourMin) * 4.0f;  // rows every 0.25 dB/oct
  uint32_t i = static_cast<uint32_t>(x);
  if (i > kNoiseColourRows - 2) i = kNoiseColourRows - 2;
  const float fr = x - static_cast<float>(i);
  const float* a = kNoiseColourTable[i];
  const float* b = kNoiseColourTable[i + 1];
  for (uint32_t k = 0; k < kNoiseColourSections; ++k) d.z[k] = a[k] + (b[k] - a[k]) * fr;
  d.gain = a[4] + (b[4] - a[4]) * fr;
  d.white = false;
  return d;
}

double noiseColourResponseDb(const NoiseColourDesign& d, double f) noexcept {
  if (d.white) return 0.0;
  const std::complex<double> w = std::polar(1.0, -2.0 * 3.14159265358979323846 * f);
  std::complex<double> h = d.gain;
  for (uint32_t k = 0; k < kNoiseColourSections; ++k)
    h *= (1.0 - static_cast<double>(d.z[k]) * w) / (1.0 - static_cast<double>(kPoles[k]) * w);
  return 20.0 * std::log10(std::abs(h));
}

float noiseFold(float x) noexcept {  // RT-safe
  if (x >= -1.0f && x <= 1.0f) return x;
  if (!(x == x)) return 0.0f;
  const float u = x + 1.0f;
  const float m = u - 4.0f * std::floor(u * 0.25f);  // [0, 4)
  return 1.0f - std::fabs(m - 2.0f);
}

