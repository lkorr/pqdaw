// Generates src/tuning/src/mos_data_tables.cpp from the ORIGINAL mos-explorer data file (T2.3).
//
//   node tools/fixtures/gen_mos_data_cpp.mjs <path to music-website/apps/web/public/mos-explorer>
//
// mos-data.js is evaluated as-is; its tables (TEMPERAMENTS, TEMP_COLORS, MOS_NAMES, MULTI_PERIOD_MOS_NAMES,
// MODE_NAMES) are written out as constant C++ data with no dynamic initialisation. tests/tuning/test_mos_data.cpp
// checks the result field by field against tests/tuning/fixtures/mos_data.json (written by gen_mos_fixtures.mjs).

import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const srcDir = process.argv[2];
if (!srcDir) {
  console.error('usage: node gen_mos_data_cpp.mjs <mos-explorer directory>');
  process.exit(2);
}
const here = path.dirname(fileURLToPath(import.meta.url));
const outFile = path.resolve(here, '../../src/tuning/src/mos_data_tables.cpp');

const dataSrc = fs.readFileSync(path.join(srcDir, 'mos-data.js'), 'utf8');
const ctx = vm.createContext({});
vm.runInContext(dataSrc + '\nglobalThis.__d = { TEMPERAMENTS, TEMP_COLORS, MOS_NAMES, MULTI_PERIOD_MOS_NAMES, MODE_NAMES };', ctx);
const D = ctx.__d;

const KNOWN_FIELDS = new Set(['name', 'mos', 'genRange', 'period', 'commas', 'commaNames', 'wikiUrl', 'description', 'disabled']);
for (const t of D.TEMPERAMENTS)
  for (const k of Object.keys(t))
    if (!KNOWN_FIELDS.has(k)) throw new Error(`temperament ${t.name}: unknown field ${k} (extend the C++ Temperament struct)`);

// C++ string literal; non-ASCII stays raw UTF-8 (the build uses /utf-8).
function str(s) {
  let out = '"';
  for (const ch of s) {
    const c = ch.codePointAt(0);
    if (ch === '"') out += '\\"';
    else if (ch === '\\') out += '\\\\';
    else if (ch === '\n') out += '\\n';
    else if (ch === '\t') out += '\\t';
    else if (c < 0x20) out += '\\' + c.toString(8).padStart(3, '0');
    else out += ch;
  }
  return out + '"';
}
// Double literal that parses back to the same value (JS shortest round-trip form).
function num(x) {
  if (!Number.isFinite(x)) throw new Error(`non-finite number ${x}`);
  const s = String(x);
  return /[.e]/.test(s) ? s : s + '.0';
}
function key(k) {
  const m = /^(\d+)L_(\d+)s$/.exec(k);
  if (!m) throw new Error(`bad MOS key ${k}`);
  return `{${+m[1]}, ${+m[2]}}`;
}

const L = [];
L.push('// GENERATED by tools/fixtures/gen_mos_data_cpp.mjs from mos-explorer/mos-data.js. Do not edit by hand:');
L.push('// regenerate instead. Checked against tests/tuning/fixtures/mos_data.json by tests/tuning/test_mos_data.cpp.');
L.push('');
L.push('#include "mos_data_tables.h"');
L.push('');
L.push('namespace pq::tuning::detail {');
L.push('namespace {');
L.push('');
D.TEMPERAMENTS.forEach((t, i) => {
  const mos = Array.isArray(t.mos) ? t.mos : [t.mos];
  L.push(`constexpr MosKey kT${i}Mos[] = {${mos.map(key).join(', ')}};`);
  if ((t.commas || []).length) L.push(`constexpr std::string_view kT${i}Commas[] = {${t.commas.map(str).join(', ')}};`);
  if ((t.commaNames || []).length) L.push(`constexpr std::string_view kT${i}CommaNames[] = {${t.commaNames.map(str).join(', ')}};`);
});
L.push('');
D.TEMPERAMENTS.forEach((t, i) => {
  L.push(`constexpr std::string_view kT${i}Description = ${str(t.description ?? '')};`);
});
L.push('');
for (const [k, names] of Object.entries(D.MODE_NAMES))
  L.push(`constexpr std::string_view kModes_${k}[] = {${names.map(str).join(', ')}};`);
L.push('');
L.push('}  // namespace');
L.push('');
L.push('const Temperament kTemperaments[] = {');
D.TEMPERAMENTS.forEach((t, i) => {
  const commas = (t.commas || []).length ? `kT${i}Commas` : '{}';
  const commaNames = (t.commaNames || []).length ? `kT${i}CommaNames` : '{}';
  L.push(`    {${str(t.name)}, kT${i}Mos, ${num(t.genRange[0])}, ${num(t.genRange[1])}, ` +
    `${num(t.period || 1200)}, ${t.period !== undefined}, ${commas}, ${commaNames}, ` +
    `${str(t.wikiUrl ?? '')}, kT${i}Description, ${!!t.disabled}},`);
});
L.push('};');
L.push(`const size_t kTemperamentCount = ${D.TEMPERAMENTS.length};`);
L.push('');
const pairs = (obj, valFn) => Object.entries(obj).map(([k, v]) => `    {${valFn(k)}, ${str(v)}},`);
L.push('const NamedColor kTemperamentColors[] = {');
L.push(...Object.entries(D.TEMP_COLORS).map(([k, v]) => `    {${str(k)}, ${str(v)}},`));
L.push('};');
L.push(`const size_t kTemperamentColorCount = ${Object.keys(D.TEMP_COLORS).length};`);
L.push('');
L.push('const MosNameEntry kMosNames[] = {');
L.push(...pairs(D.MOS_NAMES, key));
L.push('};');
L.push(`const size_t kMosNameCount = ${Object.keys(D.MOS_NAMES).length};`);
L.push('');
L.push('const MosNameEntry kMultiPeriodMosNames[] = {');
L.push(...pairs(D.MULTI_PERIOD_MOS_NAMES, key));
L.push('};');
L.push(`const size_t kMultiPeriodMosNameCount = ${Object.keys(D.MULTI_PERIOD_MOS_NAMES).length};`);
L.push('');
L.push('const ModeNameEntry kModeNames[] = {');
for (const k of Object.keys(D.MODE_NAMES)) L.push(`    {${key(k)}, kModes_${k}},`);
L.push('};');
L.push(`const size_t kModeNameCount = ${Object.keys(D.MODE_NAMES).length};`);
L.push('');
L.push('}  // namespace pq::tuning::detail');
fs.writeFileSync(outFile, L.join('\n') + '\n');
console.log(`wrote ${outFile}: ${D.TEMPERAMENTS.length} temperaments`);
